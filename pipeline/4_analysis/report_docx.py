def shade(cell, hex_color: str):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def clean(s) -> str:
    s = "" if s is None else str(s)
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", " ", s)    # characters forbidden in XML


def add_table(doc, headers, rows, widths=None, font=8, header_fill="1F3864"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0]
    set_repeat_header(hdr)
    for i, h in enumerate(headers):
        c = hdr.cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(clean(h))
        r.bold = True
        r.font.size = Pt(font)
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        shade(c, header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            fill = None
            if isinstance(v, tuple):          # (text, background colour)
                v, fill = v
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(clean(v))
            run.font.size = Pt(font)
            if fill:
                shade(cells[i], fill)
                run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
                run.bold = True
    if widths:
        t.autofit = False
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def kv_table(doc, pairs, widths=(4.5, 12.5), font=9):
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    for k, v in pairs:
        cells = t.add_row().cells
        cells[0].text, cells[1].text = "", ""
        r = cells[0].paragraphs[0].add_run(clean(k))
        r.bold = True
        r.font.size = Pt(font)
        shade(cells[0], "D9E2F3")
        fill = None
        if isinstance(v, tuple):
            v, fill = v
        r2 = cells[1].paragraphs[0].add_run(clean(v))
        r2.font.size = Pt(font)
        if fill:
            shade(cells[1], fill)
            r2.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            r2.bold = True
    for row in t.rows:
        row.cells[0].width, row.cells[1].width = Cm(widths[0]), Cm(widths[1])
    doc.add_paragraph()
    return t


def para(doc, text, bold=False, italic=False, size=None, style=None):
    for block in clean(text).split("\n\n"):
        p = doc.add_paragraph(style=style)
        lines = block.split("\n")
        for i, line in enumerate(lines):
            r = p.add_run(line)
            r.bold, r.italic = bold, italic
            if size:
                r.font.size = Pt(size)
            if i < len(lines) - 1:
                r.add_break()
    return p


def bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.add_run(clean(text))
    return p


def add_toc(doc):
    p = doc.add_paragraph()
    run = p.add_run()
    for tag, text in (("begin", None), (None, 'TOC \\o "1-3" \\h \\z \\u'), ("separate", None), (None, None), ("end", None)):
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
            run._r.append(el)
        elif text:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
            run._r.append(el)
        else:
            t = OxmlElement("w:t")
            t.text = "Table of contents: right-click > Update Field (or F9) to display it."
            run._r.append(t)


def new_section(doc, landscape: bool):
    sec = doc.add_section()
    w, h = sec.page_width, sec.page_height
    if landscape and w < h or not landscape and w > h:
        sec.page_width, sec.page_height = h, w
    sec.orientation = WD_ORIENT.LANDSCAPE if landscape else WD_ORIENT.PORTRAIT
    return sec


def evidence_rows(evs, max_desc=350):
    rows = []
    for e in evs:
        rows.append([e.get("ts") or "", e.get("artifact") or "", (e.get("ts_desc") or "") + ("\n" if e.get("ts_desc") else "")
                     + (e.get("path") or "") + ("\n" if e.get("path") else "") + (e.get("description") or "")[:max_desc],
                     e.get("ref") or "", e.get("evidence") or ""])
    return rows


def confidence_rows(x: dict) -> list:
    """Independent sources, evidence-policy notes and analyst override of a finding or an answer."""
    rows = []
    if x.get("sources"):
        rows.append(("Independent sources", "\n".join(x["sources"])))
    if x.get("confidence_notes"):
        rows.append(("Evidence policy", "\n".join(x["confidence_notes"])))
    if any(e.get("mapping") == "auto" for e in x.get("evidence", [])):
        rows.append(("Mapping", "some evidence comes from outputs mapped automatically (not validated): check the raw records"))
    ov = x.get("analyst_override") or {}
    if ov.get("confidence"):
        rows.append(("Analyst override", f"{ov['confidence']} by {ov.get('by') or '?'}: {ov.get('reason') or '(no reason given)'}"))
    return rows


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def integrity_text(raw) -> str:
    """Result of the KAPE SHA-1 check (inventory.py), stored as JSON in meta."""
    try:
        i = json.loads(raw) if raw and raw != "not checked" else None
    except (TypeError, ValueError):
        i = None
    if not i:
        return "not checked (run the inventory again with a recent version of the pipeline)"
    txt = (f"{i.get('verdict')}: {i.get('ok', 0)} file(s) matching the SHA-1 recorded by KAPE, "
           f"{i.get('mismatch', 0)} different, {i.get('missing', 0)} missing, "
           f"{i.get('no_reference', 0)} without KAPE hash, {i.get('live_copy_mismatch', 0)} expected difference(s) on "
           f"files copied live in raw mode (checked on {i.get('checked_at')})")
    if i.get("live_copy_examples"):
        txt += "\nExpected differences (raw live copy: $MFT, $LogFile...): " + ", ".join(i["live_copy_examples"][:10])
    if i.get("mismatch_examples"):
        txt += "\nUNEXPLAINED DIFFERENCES (file modified since collection): " + ", ".join(i["mismatch_examples"][:10])
    if "changed_during_parsing" in i:
        ch = i["changed_during_parsing"]
        txt += ("\nAfter parsing: " + (f"{len(ch)} file(s) MODIFIED during parsing: " + ", ".join(ch[:10]) if ch
                                       else "no collection file modified by parsing"))
    return txt


