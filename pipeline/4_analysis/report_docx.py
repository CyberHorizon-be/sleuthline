"""
Sleuthline - incident response Word report, generated from findings.json (analyze.py) and the
DuckDB database of the case. The analytical content comes from the agent; everything else
(scope, tools, versions, evidence, traceability) is extracted directly from the database and
the case files.

Every finding, event and IOC comes with its evidence: UTC timestamp, artifact, detail,
reference (<output>#<record>) and original path on the machine.
"""
