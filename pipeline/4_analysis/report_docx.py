# ------------------------------------------------------------------------------------------
# Text helpers
# ------------------------------------------------------------------------------------------
def clean(s) -> str:
    s = "" if s is None else str(s)
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", " ", s)    # characters forbidden in XML


def esc(s) -> str:
    return xml_escape(clean(s))


def short_ts(s) -> str:
    """2020-09-19 02:39:58.411571 -> 2020-09-19 02:39:58 (the full value stays in findings.json and the CSV exports)."""
    s = clean(s)
    return s[:19] if re.match(r"\d{4}-\d\d-\d\d[ T]\d\d:\d\d:\d\d\.\d+", s) else s


def period(a, b) -> str:
    a, b = short_ts(a or "?"), short_ts(b or "?")
    return a if a == b else f"{a} – {b}"


def first_sentence(s: str, limit=170) -> str:
    s = re.sub(r"\s+", " ", re.sub(r"[*`#]", "", clean(s))).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", s)
    s = m.group(1) if m else s
    return s if len(s) <= limit else s[:limit - 1].rsplit(" ", 1)[0] + "…"


def technique_id(t: str) -> str | None:
    m = re.search(r"T\d{4}(?:\.\d{3})?", t or "")
    return m.group(0) if m else None


def technique_info(tid: str) -> tuple[str, str]:
    base = tid.split(".")[0]
    tactic = (MITRE.get(base) or (None, ""))[0] or ""
    if "." in tid and tid in MITRE:
        return tactic, f"{MITRE.get(base, (None, ''))[1]}: {MITRE[tid][1]}".lstrip(": ")
    return tactic, (MITRE.get(tid) or (None, ""))[1]


