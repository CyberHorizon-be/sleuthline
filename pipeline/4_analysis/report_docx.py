def case_sources_line(db) -> str:
    try:
        from analyze import sources_line
        return sources_line(db.sources())
    except Exception:
        return "?"


def conservation_text(db) -> str | None:
    """'all 412 checks ok (no record lost between the tools and the database)' or the failures."""
    if not db.has_table("conservation"):
        return None
    cnt = dict(db.run("SELECT status, count(*) FROM conservation GROUP BY 1", max_rows=10)[1])
    if not cnt.get("fail") and not cnt.get("warn"):
        return f"all {cnt.get('ok', 0)} checks ok (no record lost between the tools and the database)"
    bad = db.run("SELECT src_file, \"check\", expected, actual, note FROM conservation WHERE status = 'fail' "
                 "ORDER BY 1 LIMIT 10", max_rows=10)[1]
    txt = f"{cnt.get('ok', 0)} checks ok, {cnt.get('warn', 0)} warning(s), {cnt.get('fail', 0)} failure(s)"
    if bad:
        txt += ": " + "; ".join(f"{a} ({b}: expected {c}, got {d_}{', ' + e if e else ''})" for a, b, c, d_, e in bad)
    return txt


def memory_host(db) -> str | None:
    """Host name from the memory image (COMPUTERNAME of the processes), when no disk artifact gives one."""
    if "vol_envars" not in getattr(db, "raw_tables", set()):
        return None
    try:
        rows = db.run("SELECT \"Value\", count(*) FROM raw.vol_envars WHERE \"Variable\" = 'COMPUTERNAME' "
                      "AND \"Value\" IS NOT NULL GROUP BY 1 ORDER BY 2 DESC LIMIT 1", max_rows=1)[1]
    except Exception:
        return None
    return f"{rows[0][0]} (memory image)" if rows else None


def build_report(case: Path, out: Path, d: dict, db, guidance: dict, steps: list, pcfg: dict, log) -> Path:
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10)
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)
        s.top_margin = s.bottom_margin = Cm(1.8)

    meta = dict(db.run("SELECT key, value FROM meta", max_rows=100)[1])
    hosts = db.run("SELECT host, count(*) n FROM timeline WHERE host IS NOT NULL AND host <> '' GROUP BY 1 ORDER BY 2 DESC LIMIT 10",
                   max_rows=10)[1]
    users = db.run("SELECT user_name, count(*) n FROM timeline WHERE user_name IS NOT NULL AND user_name <> '' "
                   "GROUP BY 1 ORDER BY 2 DESC LIMIT 15", max_rows=15)[1]
    tl_span = db.run("SELECT count(*), min(ts), max(ts) FROM timeline", max_rows=1)[1][0]
    # Bulk of the traces (0.1 % - 99.9 %): a few aberrant dates (1601, 1980, future) are common in artifacts
    tl_bulk = db.run("SELECT quantile_disc(ts, 0.001), quantile_disc(ts, 0.999) FROM timeline", max_rows=1)[1][0]
    findings = sorted(d["findings"], key=lambda f: (SEV_ORDER.get(f["severity"], 9), f.get("first_ts") or ""))
    by_sev = defaultdict(int)
    for f in d["findings"]:
        by_sev[f["severity"]] += 1
    events = sorted(d["timeline_events"], key=lambda e: e.get("ts") or "")
    gen = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    main_host = hosts[0][0] if hosts else memory_host(db) or "?"
    period = guidance.get("period") or {}

    # ---- Cover page --------------------------------------------------------------------
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for _ in range(6):
        p.add_run().add_break()
    r = p.add_run("INCIDENT RESPONSE REPORT")
    r.bold, r.font.size, r.font.color.rgb = True, Pt(26), RGBColor(0x1F, 0x38, 0x64)
    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p2.add_run(f"Forensic analysis: {case.name}")
    r.font.size = Pt(16)
    doc.add_paragraph()
    kv_table(doc, [("Case", case.name), ("Main system", main_host),
                   ("Verdict", d.get("summary", {}).get("verdict") or "see summary"),
                   ("Trace period (UTC)", f"{tl_bulk[0]} → {tl_bulk[1]} (99.8 % of the events; full range {tl_span[1]} → {tl_span[2]})"),
                   ("Incident window (UTC)", f"{(d.get('incident_window') or {}).get('start') or '?'} → {(d.get('incident_window') or {}).get('end') or '?'}"),
                   ("Findings", ", ".join(f"{SEV_LABEL[k]}: {by_sev[k]}" for k in SEV_LABEL if by_sev[k]) or "none"),
                   ("Report date", gen), ("Classification", "CONFIDENTIAL: TLP:AMBER"),
                   ("Production", f"{TOOL_NOTE} Model: {pcfg.get('provider')} / {pcfg.get('model')}.")])
    para(doc, "Disclaimer: this report was produced automatically. Every finding is linked to verifiable records of the case "
              "database (\"Reference\" column) and to the original path of the artifact. It must be reviewed and validated by "
              "an analyst before any distribution or decision.", italic=True, size=8)
    doc.add_page_break()
    doc.add_heading("Table of contents", level=1)
    add_toc(doc)
    doc.add_page_break()

    # ---- 1. Summary ----------------------------------------------------------------------
    sm = d.get("summary") or {}
    doc.add_heading("1. Executive summary", level=1)
    if sm.get("verdict"):
        para(doc, "Verdict: " + sm["verdict"], bold=True)
    para(doc, sm.get("executive_summary") or "(summary not produced: summary step not run)")
    doc.add_heading("Key figures", level=2)
    kv_table(doc, [("Findings", f"{len(d['findings'])} ("
                    + ", ".join(f"{SEV_LABEL[k].lower()}: {by_sev[k]}" for k in SEV_LABEL if by_sev[k]) + ")"),
                   ("Key timeline events", str(len(events))),
                   ("Indicators of compromise", str(len(d["iocs"]))),
                   ("Questions answered", f"{len(d['answers'])} / {len(guidance['questions'])} asked in the guidance"),
                   ("First / last key event (UTC)", f"{events[0]['ts'] if events else '?'} → {events[-1]['ts'] if events else '?'}")])
    if findings:
        doc.add_heading("Main findings", level=2)
        add_table(doc, ["ID", "Severity", "Confidence", "Finding", "Period (UTC)"],
                  [[f["id"], (SEV_LABEL[f["severity"]], SEV_COLOR[f["severity"]]), shown_confidence(f), f["title"],
                    f"{f.get('first_ts') or '?'} → {f.get('last_ts') or '?'}"] for f in findings if f["severity"] != "info"][:40],
                  widths=[1.4, 2, 2, 8, 4])
    if sm.get("technical_summary"):
        doc.add_heading("Technical assessment", level=2)
        para(doc, sm["technical_summary"])

    # ---- 2. Scope and method -------------------------------------------------------------
    doc.add_heading("2. Scope, sources and methodology", level=1)
    doc.add_heading("2.1 Analyzed system", level=2)
    kv_table(doc, [("Evidence of the case", case_sources_line(db)),
                   ("Observed host names", ", ".join(f"{h} ({n})" for h, n in hosts) or (memory_host(db) or "?")),
                   ("Observed accounts", ", ".join(f"{u} ({n})" for u, n in users) or "?"),
                   ("Machine time zone", f"ActiveTimeBias = {meta.get('machine_active_time_bias_min')} min (UTC = local time + bias)"),
                   ("Time convention of the report", "All times are UTC."),
                   ("Available traces", f"{tl_span[0]:,} timeline events, from {tl_span[1]} to {tl_span[2]}")])
    doc.add_heading("2.2 Collection and processing", level=2)
    para(doc, "Evidence of the case: KAPE collection (disk), memory image (Volatility 3) and network captures (Suricata), "
              "as available (see 2.1); parsing by recognized tools orchestrated by orchestrator.py; normalization "
              "into DuckDB by normalize.py; analysis by analyze.py following the playbook. The raw tool outputs are kept in "
              f"{case}\\parsed and every cited piece of evidence points to them.")
    jobs = db.run("SELECT dir, title, status, tools, duration_s FROM jobs ORDER BY dir", max_rows=200)[1]
    rows = []
    for jd, title, status, tools, dur in jobs:
        try:
            tl = json.loads(tools or "{}") or {}
            tv = "; ".join(f"{k} {v.get('version', '')}" if isinstance(v, dict) else k for k, v in tl.items())
        except ValueError:
            tv = tools
        fill = None if status == "ok" else ("C00000" if status in ("failed", "stalled", "tool_missing") else "E36C09")
        rows.append([jd, title, (status, fill) if fill else status, tv, f"{dur or 0:.0f} s"])
    add_table(doc, ["Job", "Artifact / tool", "Status", "Tool and version", "Duration"], rows, widths=[3, 5, 1.8, 5.5, 1.5], font=7)
    norm = {}
    try:
        norm = json.loads((case / "db" / "normalize_report.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pass
    kv_table(doc, [("Analysis database", f"{case / 'db' / 'case.duckdb'}"),
                   ("Pipeline version", str(meta.get("pipeline_version") or "unknown")),
                   ("Collection integrity", integrity_text(meta.get("collection_integrity"))),
                   ("Normalization", f"normalize.py v{meta.get('normalize_version')} on {meta.get('normalized_at_utc')}; "
                                     f"mappings v{meta.get('map_version')} (sha256 {str(meta.get('map_sha256'))[:16]}…)"),
                   ("Normalization warnings", "\n".join(norm.get("warnings", [])) or "none"),
                   ("Normalization errors", "\n".join(norm.get("errors", [])) or "none"),
                   ("Outputs without a validated mapping", ", ".join(norm.get("unmapped_tables", [])) or "none")])
    doc.add_heading("2.3 Methodology", level=2)
    para(doc, "The analysis follows the playbook below (PLAYBOOK.md), one step at a time. At each step, the agent queries the "
              "read-only database, correlates the sources and records a finding only if all its evidence references exist in "
              "the database (automatic check). Artifact dates are interpreted according to their evidential value "
              "(e.g. ShimCache = presence, Prefetch = execution).")
    add_table(doc, ["Step", "Purpose", "Status", "Tool calls", "Duration"],
              [[str(s["num"]), s["title"], d["steps"].get(str(s["num"]), {}).get("status", "not run"),
                str(d["steps"].get(str(s["num"]), {}).get("tool_calls", "")),
                f"{d['steps'].get(str(s['num']), {}).get('duration_s', 0):.0f} s" if d["steps"].get(str(s["num"])) else ""] for s in steps],
              widths=[1.3, 9, 2.5, 2.2, 2])
    doc.add_heading("2.4 Guidance provided by the analyst", level=2)
    kv_table(doc, [("Context", guidance["context"].strip() or "none"),
                   ("Period of interest", ", ".join(f"{k} = {v}" for k, v in period.items()) or "not specified"),
                   ("Questions", "\n".join(f"Q{i}. {q}" for i, q in enumerate(guidance["questions"], 1)) or "none"),
                   ("Provided IOCs", "\n".join(f"{i['type']} = {i['value']}" for i in guidance["iocs"]) or "none"),
                   ("Suspects", "\n".join(guidance["suspects"]) or "none"),
                   ("Exclusions", "\n".join(guidance["exclusions"]) or "none"),
                   ("Instructions", guidance["instructions"].strip() or "none")])
    doc.add_heading("2.5 Limitations of the analysis", level=2)
    para(doc, sm.get("limitations") or "(not provided)")
    lowered = [x["id"] for x in d["findings"] if x.get("confidence_notes")]
    if lowered:
        bullet(doc, f"Confidence lowered by the evidence policy (insufficient corroboration or unvalidated mapping): {', '.join(lowered)}.")
    if d.get("injection_alerts"):
        bullet(doc, f"{len(d['injection_alerts'])} excerpt(s) of the evidence look like instructions addressed to an AI: "
                    "see the appendix \"Text addressed to an AI found in the evidence\".")
    na = [(s, v) for s, v in sorted(d["steps"].items(), key=lambda x: int(x[0]) if str(x[0]).isdigit() else 999)
          if v.get("status") == "not_applicable"]
    for s, v in na:
        bullet(doc, f"Step {s} ({v.get('title')}) not applicable: {v.get('reason')}.")
    cov_counts = dict(db.run("SELECT status, count(*) FROM coverage GROUP BY 1", max_rows=10)[1]) if db.has_table("coverage") else {}
    if cov_counts:
        bullet(doc, "Coverage of the evidence (appendix E bis): " + ", ".join(f"{k} {v}" for k, v in sorted(cov_counts.items()))
                    + ". An artifact that is not \"analyzed\" was not available to the analysis: its absence of findings "
                      "is not evidence of absence.")
    cons = conservation_text(db)
    if cons and "failure" in cons and not cons.startswith("all"):
        bullet(doc, f"Data conservation: {cons}.")
    gaps =[(s, v) for s, v in sorted(d["steps"].items(), key=lambda x: int(x[0]) if str(x[0]).isdigit() else 999) if v.get("gaps")]
    for s, v in gaps:
        bullet(doc, f"Step {s} ({v.get('title')}): {v['gaps']}")
    bad = [r for r in jobs if r[2] != "ok"]
    if bad:
        para(doc, "Incomplete parsing sources: " + ", ".join(f"{r[0]} ({r[2]})" for r in bad) + ".")

    # ---- 3. Timeline (landscape) ---------------------------------------------------------
    new_section(doc, landscape=True)
    doc.add_heading("3. Incident timeline", level=1)
    para(doc, "Key events established by the analysis (UTC), with their evidence. The complete timeline of the incident window "
              "(all artifacts) is provided in incident_timeline.csv"
              + (" (truncated to 500,000 rows: set the period in guidance.txt)." if (d.get("incident_window") or {}).get("truncated") else "."),
              size=9)
    if events:
        add_table(doc, ["Timestamp (UTC)", "Phase", "Event", "Description", "MITRE", "References"],
                  [[e["ts"], e.get("phase") or "", e["title"], e["description"], " ".join(e.get("mitre", [])),
                    "\n".join(x["ref"] for x in e["evidence"][:6])] for e in events],
                  widths=[3.3, 2.6, 4.5, 9.5, 2, 4.5], font=7)
    else:
        para(doc, "(no key event recorded)")
    doc.add_heading("Detailed evidence timeline", level=2)
    para(doc, "All the evidence cited by the findings and the timeline, sorted by time.", size=9)
    allev = {}
    for src in [*d["findings"], *d["timeline_events"], *d["iocs"]]:
        for e in src.get("evidence", []):
            allev.setdefault(e["ref"], {**e, "used_by": set()})["used_by"].add(src["id"])
    rows = sorted(allev.values(), key=lambda e: e.get("ts") or "")
    add_table(doc, ["Timestamp (UTC)", "Artifact", "Detail", "Reference", "Original source", "Cited by"],
              [[*r[:5], ", ".join(sorted(e["used_by"]))] for r, e in zip(evidence_rows(rows, 400), rows)],
              widths=[3.2, 3.5, 10, 4.3, 4.5, 1.8], font=7)

    # ---- 4. Detailed findings ------------------------------------------------------------
    new_section(doc, landscape=False)
    doc.add_heading("4. Detailed findings", level=1)
    step_titles = {str(s["num"]): s["title"] for s in steps}
    grouped = defaultdict(list)
    for f in d["findings"]:
        grouped[str(f.get("step"))].append(f)
    for snum in sorted(grouped, key=lambda x: int(x) if x.isdigit() else 999):
        doc.add_heading(f"4.{snum} {step_titles.get(snum, 'One-off questions' if snum == 'question' else snum)}", level=2)
        ssum = d["steps"].get(snum, {}).get("summary")
        if ssum:
            para(doc, ssum, italic=True, size=9)
        for f in sorted(grouped[snum], key=lambda f: (SEV_ORDER.get(f["severity"], 9), f.get("first_ts") or "")):
            doc.add_heading(f"{f['id']}: {f['title']}", level=3)
            kv_table(doc, [("Severity", (SEV_LABEL[f["severity"]], SEV_COLOR[f["severity"]])), ("Confidence", shown_confidence(f)),
                           *confidence_rows(f),
                           ("Category", f.get("category") or ""), ("MITRE ATT&CK", ", ".join(f.get("mitre") or []) or "n/a"),
                           ("Period (UTC)", f"{f.get('first_ts') or '?'} → {f.get('last_ts') or '?'}")])
            doc.add_paragraph().add_run("Observed facts").bold = True
            para(doc, f["description"])
            if f.get("analysis"):
                doc.add_paragraph().add_run("Analysis").bold = True
                para(doc, f["analysis"])
            doc.add_paragraph().add_run(f"Evidence ({len(f['evidence'])})").bold = True
            add_table(doc, ["UTC", "Artifact", "Detail", "Reference", "Original source"], evidence_rows(f["evidence"]),
                      widths=[2.6, 2.6, 6.4, 3, 3], font=7)

    # ---- 5. IOCs -------------------------------------------------------------------------
    doc.add_heading("5. Indicators of compromise", level=1)
    if d["iocs"]:
        add_table(doc, ["ID", "Type", "Value", "Context", "First seen (UTC)", "Last seen (UTC)", "References"],
                  [[i["id"], i["type"], i["value"], i["context"], i.get("first_seen") or "", i.get("last_seen") or "",
                    "\n".join(e["ref"] for e in i["evidence"][:5])] for i in d["iocs"]],
                  widths=[1.2, 1.6, 4.2, 4.2, 2.2, 2.2, 3], font=7)
    else:
        para(doc, "(no IOC recorded)")

    # ---- 6. MITRE ------------------------------------------------------------------------
    doc.add_heading("6. MITRE ATT&CK mapping", level=1)
    tech = defaultdict(set)
    for x in [*d["findings"], *d["timeline_events"]]:
        for t in x.get("mitre") or []:
            tech[t.strip()].add(x["id"])
    if tech:
        add_table(doc, ["Technique", "Findings / events"], [[t, ", ".join(sorted(v))] for t, v in sorted(tech.items())],
                  widths=[4, 13], font=8)
    else:
        para(doc, "(no associated technique)")

    # ---- 7. Questions --------------------------------------------------------------------
    doc.add_heading("7. Answers to the questions", level=1)
    answered = {a["question"] for a in d["answers"]}
    for a in d["answers"]:
        doc.add_heading(a["question"], level=3)
        kv_table(doc, [("Confidence", shown_confidence(a)), *confidence_rows(a)])
        para(doc, a["answer"])
        if a.get("evidence"):
            add_table(doc, ["UTC", "Artifact", "Detail", "Reference", "Original source"], evidence_rows(a["evidence"]),
                      widths=[2.6, 2.6, 6.4, 3, 3], font=7)
    for q in guidance["questions"]:
        if q not in answered:
            doc.add_heading(q, level=3)
            para(doc, "(question not addressed by the analysis)", italic=True)
    if not d["answers"] and not guidance["questions"]:
        para(doc, "(no question asked)")

    # ---- 8. Recommendations --------------------------------------------------------------
    doc.add_heading("8. Recommendations", level=1)
    recs = d.get("recommendations") or {}
    if recs:
        for k, label in REC_LABEL.items():
            if recs.get(k):
                doc.add_heading(label, level=2)
                for item in recs[k]:
                    bullet(doc, item)
    else:
        para(doc, "(not produced)")

    # ---- Appendices ----------------------------------------------------------------------
    doc.add_heading("Appendix A: Summary of the analysis steps", level=1)
    for s in steps:
        v = d["steps"].get(str(s["num"]))
        doc.add_heading(f"Step {s['num']}: {s['title']}", level=3)
        if not v:
            para(doc, "(not run)", italic=True)
            continue
        para(doc, v.get("summary") or "")
        if v.get("gaps"):
            para(doc, "Not verified: " + v["gaps"], italic=True, size=9)

    doc.add_heading("Appendix B: Automatic detections", level=1)
    cnt = db.run("SELECT engine, level, count(*) FROM detections GROUP BY ALL ORDER BY 1, 3 DESC", max_rows=100)[1]
    add_table(doc, ["Engine", "Level", "Count"], [[a, b, str(c)] for a, b, c in cnt], widths=[4, 4, 3])
    top = db.run("SELECT ts, engine, level, rule_title, computer, channel, event_id, record_id, ref FROM detections "
                 "WHERE level IN ('critical', 'high') ORDER BY ts LIMIT 400", max_rows=400)[1]
    if top:
        para(doc, "Critical and high detections (to compare with the findings; a detection is not a finding until it has "
                  "been qualified):", size=9)
        add_table(doc, ["UTC", "Engine", "Level", "Rule", "Host", "Channel", "EventID", "RecordID", "Reference"],
                  [[str(x) if x is not None else "" for x in r] for r in top],
                  widths=[2.4, 1.6, 1.3, 4, 2, 2, 1.1, 1.1, 2.5], font=6)

    if d.get("notes"):
        doc.add_heading("Appendix C: Working notes (leads ruled out, false positives)", level=1)
        for n in d["notes"]:
            bullet(doc, f"[step {n.get('step')}] {n['text']}")

    if d.get("injection_alerts"):
        doc.add_heading("Appendix C bis: Text addressed to an AI found in the evidence", level=1)
        para(doc, "During the analysis, the program found in the case data text that looks like instructions addressed to an AI "
                  "model or an analyst. It was passed to the model as untrusted data and never followed. Such text can be an "
                  "attempt to mislead an automated analysis (anti-forensics) and should be reviewed by the analyst.", size=9)
        add_table(doc, ["Step", "Tool / query", "Excerpt"],
                  [[str(a.get("step")), f"{a.get('tool')}: {a.get('query') or ''}", a.get("excerpt") or ""]
                   for a in d["injection_alerts"][:200]], widths=[1.3, 5.5, 10.2], font=7)

    if d.get("ioc_sweep"):
        doc.add_heading("Appendix D: Automatic sweep of the provided IOCs", level=1)
        add_table(doc, ["Type", "Value", "Timeline", "Raw tables (rows)"],
                  [[r["type"], r["value"], str(r["timeline_hits"]),
                    "\n".join(f"{h['table']}: {h['count']}" for h in r["raw_hits"]) or "none"] for r in d["ioc_sweep"]["results"]],
                  widths=[2, 6, 2, 7], font=8)

    doc.add_heading("Appendix E: Artifact coverage", level=1)
    cov = db.run("SELECT artifact, tool, mapping, rows, first_ts, last_ts FROM artifact_summary", max_rows=500)[1]
    add_table(doc, ["Artifact", "Tool", "Mapping", "Events", "First (UTC)", "Last (UTC)"],
              [[str(x) if x is not None else "" for x in r] for r in cov], widths=[5, 2.5, 2, 1.8, 3, 3], font=7)

    if db.has_table("coverage"):
        doc.add_heading("Appendix E bis: Coverage of the evidence", level=1)
        para(doc, "Computed by the program from the inventory, the parsing jobs and the loaded tables. not_collected: absent "
                  "from the case; not_covered: no installed tool; not_parsed: the tool failed or did not run; empty: parsed, "
                  "no record; analyzed: records in the database.", size=9)
        cnt = db.run("SELECT source, status, count(*), sum(rows) FROM coverage GROUP BY ALL ORDER BY 1, 2", max_rows=50)[1]
        add_table(doc, ["Source", "Status", "Artifacts", "Records"], [[a, b, str(c), str(n or 0)] for a, b, c, n in cnt],
                  widths=[3, 3, 2.5, 3])
        rows = db.run("SELECT artifact, source, status, tool, detail FROM coverage WHERE status <> 'analyzed' "
                      "ORDER BY source, status, artifact", max_rows=300)[1]
        if rows:
            add_table(doc, ["Artifact", "Source", "Status", "Tool", "Detail"],
                      [[str(x) if x is not None else "" for x in r] for r in rows], widths=[5.5, 1.6, 2.2, 2.5, 5.2], font=7)

    doc.add_heading("Appendix F: Traceability", level=1)
    dbp = case / "db" / "case.duckdb"
    usage = d.get("usage", {})
    runs = d.get("runs", [])
    kv_table(doc, [("DuckDB database", f"{dbp}\nSHA-256 {sha256_file(dbp)}"),
                   ("Pipeline version", str(meta.get("pipeline_version") or "unknown")),
                   ("Collection integrity", integrity_text(meta.get("collection_integrity"))),
                   ("Normalization mappings", f"v{meta.get('map_version')} sha256 {meta.get('map_sha256')}"),
                   ("Data conservation", conservation_text(db) or "not checked (database normalized before 1.1)"),
                   ("Model", f"{pcfg.get('provider')} / {pcfg.get('model')}"),
                   ("Agent runs", "\n".join(f"{r.get('started')} → {r.get('ended')}: {r.get('provider')}/{r.get('model')}, "
                                            f"playbook sha256 {str(r.get('playbook_sha256'))[:16]}…" for r in runs) or "?"),
                   ("Usage", f"{usage.get('input_tokens', 0):,} input tokens (of which {usage.get('cache_read_tokens', 0):,} read "
                             f"from cache), {usage.get('output_tokens', 0):,} output tokens, {usage.get('calls', 0)} calls"),
                   ("Full trace", str(out / "transcript.jsonl") + ": every SQL query, result and model answer"),
                   ("Analysis state", str(out / "findings.json")),
                   ("Exports", "iocs.csv, key_timeline.csv, incident_timeline.csv"),
                   ("Reference format", meta.get("ref_format") or "<output>#<record number>"),
                   ("Report generated on", gen)])

    path = out / f"report_{re.sub(r'[^A-Za-z0-9_-]+', '_', case.name)}_{dt.datetime.now():%Y%m%d_%H%M}.docx"
    doc.save(str(path))
    return path
